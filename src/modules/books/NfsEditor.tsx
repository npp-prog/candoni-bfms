import { NFS_LIMITS, defaultNfsNotes, nfsNarrativeId, type BarangayId, type NfsNarrativeDoc, type NfsNarrativeVersionDoc, type NfsNote } from '@bfms/shared';
import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { reportHref } from '../../components/source';
import { ConfirmDialog, Icon, Spinner, StatusChip } from '../../components/ui';
import { useAuth } from '../../contexts/AuthContext';
import { useBarangay } from '../../contexts/BarangayContext';
import { useToast } from '../../contexts/ToastContext';
import { useCollection } from '../../hooks/useCollection';
import { useDocument } from '../../hooks/useDocument';
import { callFn, errorMessage } from '../../services/functions/api';

const saveNfsNarrative = callFn<{ barangayId: BarangayId; fiscalYear: number; notes: NfsNote[]; expectedVersion?: number }, { id: string; version: number }>('saveNfsNarrative');

/**
 * Narrative notes of the NFS (nfsNarratives/{bid}_{fy}). The numeric schedules (cash, receivables,
 * PPE, payables) are generated by the NFS report and are not edited here. Saving creates a new
 * version; the server rejects the save if someone else saved in between (expectedVersion).
 */
export function NfsEditor() {
  const { can } = useAuth();
  const { barangayId, barangayLabel, fiscalYear } = useBarangay();
  const { notify } = useToast();
  const id = barangayId ? nfsNarrativeId(barangayId, fiscalYear) : null;
  const { data, loading } = useDocument<NfsNarrativeDoc>('nfsNarratives', id);
  const versions = useCollection<NfsNarrativeVersionDoc>(id ? `nfsNarratives/${id}/versions` : 'nfsNarratives', id && data ? [] : null);
  const [notes, setNotes] = useState<NfsNote[] | null>(null);
  const [base, setBase] = useState<number>(0);
  const [dirty, setDirty] = useState(false);
  const [busy, setBusy] = useState(false);
  const [remove, setRemove] = useState<number | null>(null);

  // Load the saved text (or the standard template) once per document version, unless the user is editing.
  useEffect(() => {
    if (loading || dirty) return;
    setNotes(data?.notes?.length ? data.notes : defaultNfsNotes(barangayLabel.replace(/^Barangay\s+/i, ''), fiscalYear));
    setBase(data?.version ?? 0);
  }, [data, loading, dirty, barangayLabel, fiscalYear]);

  if (!barangayId) return null;
  if (loading || !notes) return <Spinner label="Loading notes…" />;
  const final = data?.status === 'FINAL';
  const editable = can('nfs.edit', barangayId) && !final;
  const edit = (next: NfsNote[]) => { setNotes(next); setDirty(true); };
  const set = (i: number, k: keyof NfsNote, v: string) => edit(notes.map((n, j) => (j === i ? { ...n, [k]: v } : n)));
  const move = (i: number, d: -1 | 1) => { const n = [...notes]; [n[i], n[i + d]] = [n[i + d]!, n[i]!]; edit(n); };
  const invalid = notes.some((n) => n.title.trim().length < 2);
  const stale = dirty && (data?.version ?? 0) !== base;

  async function save() {
    setBusy(true);
    try {
      const r = await saveNfsNarrative({ barangayId: barangayId!, fiscalYear, notes: notes!.map((n) => ({ title: n.title.trim(), body: n.body })), expectedVersion: base });
      notify(`Notes saved (version ${r.version}).`, 'success');
      setBase(r.version);
      setDirty(false);
    } catch (e) {
      notify(errorMessage(e), 'error');
    } finally {
      setBusy(false);
    }
  }

  return (
    <div className="space-y-4">
      <div className="card flex flex-wrap items-center gap-3 p-4">
        <div className="mr-auto text-sm text-slate-700">
          <p className="font-semibold text-navy-800">Notes to Financial Statements — FY {fiscalYear}</p>
          <p className="text-xs text-slate-600">
            {data ? <>Version {data.version} <StatusChip status={data.status} /></> : 'Not yet saved — showing the standard template.'}
            {dirty && <span className="ml-2 font-medium text-amber-800">Unsaved changes</span>}
          </p>
        </div>
        <Link className="btn-secondary" to={reportHref('NFS', { fiscalYear })}><Icon name="file" /> Preview NFS</Link>
        {editable && <button type="button" className="btn-primary" disabled={busy || !dirty || invalid} onClick={() => void save()}>{busy ? 'Saving…' : 'Save notes'}</button>}
      </div>
      {final && <p className="rounded-md border border-slate-300 bg-slate-50 px-4 py-3 text-sm text-slate-700">These notes are final and can no longer be edited.</p>}
      {!can('nfs.edit', barangayId) && !final && <p className="text-sm text-slate-600">Read only: editing requires the Municipal Accountant or Accounting Reviewer role.</p>}
      {stale && <p role="alert" className="rounded-md border border-amber-300 bg-amber-50 px-4 py-3 text-sm text-amber-900">Someone saved a newer version (v{data?.version}) while you were editing. Saving will be refused; copy your changes, then reload.</p>}
      <p className="text-xs text-slate-600">Numbered schedules for cash, receivables, property and equipment, and payables follow these notes automatically in the report. Separate paragraphs with a blank line.</p>
      <ol className="space-y-4">
        {notes.map((n, i) => (
          <li key={i} className="card p-4">
            <div className="flex flex-wrap items-end gap-2">
              <div className="min-w-[14rem] flex-1">
                <label className="label required" htmlFor={`nt-${i}`}>Note {i + 1} title</label>
                <input id={`nt-${i}`} className="input" disabled={!editable} value={n.title} maxLength={NFS_LIMITS.maxTitle} aria-invalid={n.title.trim().length < 2 ? true : undefined} onChange={(e) => set(i, 'title', e.target.value)} />
              </div>
              {editable && (
                <div className="flex gap-1">
                  <button type="button" className="btn-ghost btn-sm" disabled={i === 0} onClick={() => move(i, -1)} aria-label={`Move note ${i + 1} up`}>Up</button>
                  <button type="button" className="btn-ghost btn-sm" disabled={i === notes.length - 1} onClick={() => move(i, 1)} aria-label={`Move note ${i + 1} down`}>Down</button>
                  <button type="button" className="btn-ghost btn-icon text-slate-500 hover:text-red-700" disabled={notes.length <= 1} onClick={() => setRemove(i)} aria-label={`Remove note ${i + 1}`}><Icon name="trash" /></button>
                </div>
              )}
            </div>
            <label className="label mt-3" htmlFor={`nb-${i}`}>Text</label>
            <textarea id={`nb-${i}`} className="input min-h-[8rem] font-[inherit]" disabled={!editable} value={n.body} maxLength={NFS_LIMITS.maxBody} onChange={(e) => set(i, 'body', e.target.value)} />
          </li>
        ))}
      </ol>
      {editable && notes.length < NFS_LIMITS.maxNotes && (
        <button type="button" className="btn-secondary" onClick={() => edit([...notes, { title: '', body: '' }])}><Icon name="plus" /> Add note</button>
      )}
      {versions.rows.length > 0 && (
        <details className="card px-4 py-3 text-sm">
          <summary className="cursor-pointer font-medium text-navy-800">Saved versions ({versions.rows.length})</summary>
          <ul className="mt-2 divide-y divide-slate-100">
            {[...versions.rows].sort((a, b) => b.version - a.version).map((v) => (
              <li key={v.id} className="flex flex-wrap items-center gap-3 py-2">
                <span className="font-mono text-xs">v{v.version}</span>
                <span className="text-xs text-slate-600">{v.savedAt ? new Date(v.savedAt.seconds * 1000).toLocaleString('en-PH') : ''}</span>
                <span className="text-xs text-slate-600">{v.notes.length} note(s)</span>
                {editable && <button type="button" className="btn-ghost btn-sm ml-auto" onClick={() => edit(v.notes.map((x) => ({ ...x })))}>Load into editor</button>}
              </li>
            ))}
          </ul>
        </details>
      )}
      <ConfirmDialog
        open={remove !== null}
        danger
        title="Remove note"
        message={remove !== null ? `Remove note ${remove + 1} “${notes[remove]?.title ?? ''}”? The change is kept only after you save.` : ''}
        onCancel={() => setRemove(null)}
        onConfirm={() => { if (remove !== null) edit(notes.filter((_, j) => j !== remove)); setRemove(null); }}
      />
    </div>
  );
}
